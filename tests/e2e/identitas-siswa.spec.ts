import { expect, test } from '@playwright/test'

test('identitas wajib diisi, tersimpan, dan dapat diganti saat mulai lagi', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Mulai belajar' }).click()
  const dialog = page.getByRole('dialog', { name: 'Nama dan kelasmu' })
  const nama = dialog.getByLabel('Nama', { exact: true })
  const kelas = dialog.getByLabel('Kelas', { exact: true })
  const lanjut = dialog.getByRole('button', { name: 'Lanjut ke peta materi' })
  await lanjut.click()
  await expect(dialog).toBeVisible()
  await nama.fill('   ')
  await kelas.fill('XII IPA 1')
  await lanjut.click()
  await expect(dialog).toBeVisible()
  await nama.fill('  Siswa Uji  ')
  await lanjut.click()
  await expect(page).toHaveURL(/#\/peta-materi$/)
  await page.reload()
  await page.getByRole('link', { name: 'Beranda', exact: true }).click()
  await page.getByRole('button', { name: 'Mulai belajar' }).click()
  await expect(nama).toHaveValue('Siswa Uji')
  await expect(kelas).toHaveValue('XII IPA 1')
  await nama.fill('Siswa Berikutnya')
  await kelas.fill('XII 2')
  await lanjut.click()
  const siswa = await page.evaluate(() => JSON.parse(localStorage.getItem('metalab-siswa')!).state)
  expect(siswa).toEqual({ nama: 'Siswa Berikutnya', kelas: 'XII 2' })
})

test('dialog dapat dibatalkan dengan keyboard tanpa menyimpan isian', async ({ page }) => {
  await page.goto('/')
  const mulai = page.getByRole('button', { name: 'Mulai belajar' })
  await mulai.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nama', { exact: true }).fill('Belum disimpan')
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(mulai).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(dialog.getByLabel('Nama', { exact: true })).toHaveValue('')
  await dialog.getByRole('button', { name: 'Batal', exact: true }).click()
  await expect(dialog).toBeHidden()
})
